
import pandas as pd
import streamlit as st
from pathlib import Path

st.set_page_config(
    page_title="Intelligent Security Log Analyzer",
    page_icon="🔐",
    layout="wide"
)

BASE_DIR = Path(__file__).parent
LOG_FILE = BASE_DIR / "sample_auth_logs.csv"

st.title("Intelligent Security Log Analysis")
st.caption("Prototype using synthetic authentication logs")

# Load and validate the logs
try:
    df = pd.read_csv(LOG_FILE)
except FileNotFoundError:
    st.error("sample_auth_logs.csv was not found.")
    st.stop()

required = {"timestamp", "username", "source_ip", "event_type"}

if not required.issubset(df.columns):
    st.error("The CSV is missing required columns.")
    st.stop()

df["timestamp"] = pd.to_datetime(df["timestamp"], errors="coerce")
df = df.dropna(subset=["timestamp"])

# Dashboard metrics
total = len(df)
failures = int((df["event_type"] == "LOGIN_FAILURE").sum())
successes = int((df["event_type"] == "LOGIN_SUCCESS").sum())

# Build a unified alert list
alert_rows = []

# Rule 1: Three or more failed logins per username and source IP
failed = df[df["event_type"] == "LOGIN_FAILURE"]

for (username, source_ip), group in failed.groupby(
    ["username", "source_ip"]
):
    if len(group) >= 3:
        alert_rows.append({
            "timestamp": group["timestamp"].max(),
            "username": username,
            "source_ip": source_ip,
            "severity": "MEDIUM",
            "detection_rule": "Repeated Failed Logins",
            "evidence": f"{len(group)} failed attempts"
        })

# Rule 2: Successful login after at least three earlier failures
for (username, source_ip), group in df.groupby(
    ["username", "source_ip"]
):
    group = group.sort_values("timestamp")
    failures_before = 0
    detected = False

    for _, event in group.iterrows():
        if event["event_type"] == "LOGIN_FAILURE":
            failures_before += 1

        elif (
            event["event_type"] == "LOGIN_SUCCESS"
            and failures_before >= 3
            and not detected
        ):
            alert_rows.append({
                "timestamp": event["timestamp"],
                "username": username,
                "source_ip": source_ip,
                "severity": "HIGH",
                "detection_rule": "Success After Repeated Failures",
                "evidence": (
                    f"Successful login after {failures_before} "
                    "earlier failures"
                )
            })
            detected = True

# Rule 3: Username not in the prototype's known-user list
known_users = {"alice", "bob", "charlie"}
unknown = df[~df["username"].isin(known_users)]

for (username, source_ip), group in unknown.groupby(
    ["username", "source_ip"]
):
    alert_rows.append({
        "timestamp": group["timestamp"].max(),
        "username": username,
        "source_ip": source_ip,
        "severity": "MEDIUM",
        "detection_rule": "Unknown Username",
        "evidence": f"{len(group)} event(s) for an unknown username"
    })

alerts = pd.DataFrame(
    alert_rows,
    columns=[
        "timestamp", "username", "source_ip",
        "severity", "detection_rule", "evidence"
    ]
)

# Summary cards
c1, c2, c3, c4 = st.columns(4)
c1.metric("Total Events", total)
c2.metric("Failed Logins", failures)
c3.metric("Successful Logins", successes)
c4.metric("Total Alerts", len(alerts))

st.divider()

# Unified alerts table
st.subheader("Security Alerts")

if alerts.empty:
    st.success("No alerts generated by the configured rules.")
else:
    rule_filter = st.selectbox(
        "Filter alerts by detection rule",
        ["ALL"] + sorted(alerts["detection_rule"].unique().tolist())
    )

    shown_alerts = alerts.copy()

    if rule_filter != "ALL":
        shown_alerts = shown_alerts[
            shown_alerts["detection_rule"] == rule_filter
        ]

    st.dataframe(
        shown_alerts.sort_values("timestamp", ascending=False),
        use_container_width=True,
        hide_index=True
    )

    csv_data = alerts.to_csv(index=False).encode("utf-8")

    st.download_button(
        "Download All Security Alerts",
        data=csv_data,
        file_name="security_alerts.csv",
        mime="text/csv"
    )

# Event summary chart
st.subheader("Event Summary")
event_counts = (
    df["event_type"].value_counts()
    .rename_axis("Event Type")
    .reset_index(name="Count")
)
st.bar_chart(event_counts, x="Event Type", y="Count")

# Original logs
st.subheader("Authentication Logs")

event_filter = st.selectbox(
    "Filter logs by event type",
    ["ALL"] + sorted(df["event_type"].unique().tolist())
)

if event_filter == "ALL":
    filtered = df
else:
    filtered = df[df["event_type"] == event_filter]

st.dataframe(filtered, use_container_width=True, hide_index=True)

st.caption(
    "Alerts are investigation indicators, not proof of a confirmed attack. "
    "This prototype uses synthetic data and a predefined demo user list."
)
